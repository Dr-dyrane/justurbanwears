function presentation(product) {
  const { mediaSlots: presentationMediaSlots, ...descriptive } = product;
  const mediaSlots = [
    ...baseMedia,
    ...(presentationMediaSlots.includes("MODEL_FRONT") ? ["MODEL_FRONT"] : []),
    presentationMediaSlots.includes("CONSTRUCTION_DETAIL") ? "CONSTRUCTION_DETAIL" : "FABRIC_DETAIL",
    ...presentationMediaSlots.filter((slot) => slot !== "MODEL_FRONT"),
  ].filter((slot, index, slots) => slots.indexOf(slot) === index);
  const initialInventory = product.availability === "SOLD"
    ? { availability: "SOLD", onHand: 0, reserved: 0, sold: 1, returned: 0, writeOff: 0 }
    : product.availability === "RESERVED"
      ? { availability: "RESERVED", onHand: 1, reserved: 1, sold: 0, returned: 0, writeOff: 0 }
      : { availability: product.availability, onHand: 1, reserved: 0, sold: 0, returned: 0, writeOff: 0 };

  return Object.freeze({
    ...descriptive,
    modelAnchor: V4_MODEL_SLUGS.has(product.slug)
      ? MODEL_ANCHORS["lulu-v4"]
      : V3_MODEL_FRONT_SLUGS.has(product.slug) || V3_MODEL_SUPPLEMENTAL_SLUGS.has(product.slug)
        ? MODEL_ANCHORS["lulu-v3"]
        : MODEL_ANCHORS["lulu-v2"],
    media: Object.freeze(mediaSlots.map((slot) => Object.freeze({
      slot,
      src: `/shop/products/${product.slug}/${mediaFileForSlot[slot]}`,
      ...(MODEL_MEDIA_SLOTS.has(slot)
        ? {
            modelAnchorId: V4_MODEL_SLUGS.has(product.slug)
              ? "lulu-v4"
              : (
                  (slot === "MODEL_FRONT" && V3_MODEL_FRONT_SLUGS.has(product.slug))
                  || (slot !== "MODEL_FRONT" && V3_MODEL_SUPPLEMENTAL_SLUGS.has(product.slug))
                )
                ? "lulu-v3"
                : "lulu-v2",
          }
        : {}),
    }))),
    initialInventory: Object.freeze(initialInventory),
  });
}

